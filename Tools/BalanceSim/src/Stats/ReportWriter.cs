using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using ChiefComplaint.Sim.Data;

namespace ChiefComplaint.Sim.Stats
{
    public sealed class FocusResult
    {
        public string Group;
        public BatchSummary Summary;
    }

    /// <summary>Writes batch summaries as a Markdown report and the per-shift curves as CSV.</summary>
    public static class ReportWriter
    {
        private static string Pct(double v) => (v * 100).ToString("0.0", CultureInfo.InvariantCulture) + "%";
        private static string F(double v, string fmt = "0.0") => v.ToString(fmt, CultureInfo.InvariantCulture);

        public static string Markdown(IReadOnlyList<BatchSummary> batches, IReadOnlyList<FocusResult> focus, GameData data, GameConfig config,
            int baseSeed, string botDescriptions)
        {
            var sb = new StringBuilder();
            sb.AppendLine("# Chief Complaint balance report");
            sb.AppendLine();
            sb.AppendLine($"Generated by `Tools/BalanceSim` on {DateTime.UtcNow:yyyy-MM-dd} from the assets and `MainBoard.unity` in this checkout. " +
                          $"{batches.First().Runs} runs per bot, seeds {baseSeed}..{baseSeed + batches.First().Runs - 1}.");
            sb.AppendLine();

            sb.AppendLine("## Summary by bot");
            sb.AppendLine();
            sb.AppendLine("| Bot | Win rate | Avg last shift | Cured / run | Deaths / run | Rep at win (p50) | Funding earned / run | Reached Ambulances | Reached Trauma |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|---|");
            foreach (BatchSummary b in batches)
            {
                double cured = b.Pools.Sum(p => p.CuresPerRun), deaths = b.Pools.Sum(p => p.DeathsPerRun);
                sb.AppendLine($"| {b.Label} | {Pct(b.WinRate)} ± {Pct(b.WinRateCi95)} | {F(b.AvgLastShift)} | {F(cured)} | {F(deaths)} | " +
                              $"{(b.FinalReputationOfWinners.N > 0 ? F(b.FinalReputationOfWinners.P50, "0") : "-")} | {F(b.FundingEarnedPerRun)} | " +
                              $"{Pct(b.AmbulanceReachedShare)} | {Pct(b.TraumaReachedShare)} |");
            }
            sb.AppendLine();
            sb.AppendLine(botDescriptions);
            sb.AppendLine();

            sb.AppendLine("## Death and cure rates by patient pool");
            sb.AppendLine();
            sb.AppendLine("Rates are shares of the patients of that pool who arrived. \"Open\" means still on the board when the run ended.");
            sb.AppendLine();
            sb.AppendLine("| Bot | Pool | Arrivals / run | Cured | Died | Open | Shifts to cure |");
            sb.AppendLine("|---|---|---|---|---|---|---|");
            foreach (BatchSummary b in batches)
                foreach (PoolStats p in b.Pools.Where(p => p.ArrivalsPerRun > 0))
                    sb.AppendLine($"| {b.Label} | {p.Pool} | {F(p.ArrivalsPerRun, "0.00")} | {Pct(p.CureRate)} | {Pct(p.DeathRate)} | {Pct(p.UnresolvedRate)} | {F(p.AvgShiftsToCure)} |");
            sb.AppendLine();

            foreach (BatchSummary b in batches)
            {
                sb.AppendLine($"## Curves: {b.Label}");
                sb.AppendLine();
                sb.AppendLine("End of each shift, over runs still alive. Rep and Funding as p10 / median / p90.");
                sb.AppendLine();
                sb.AppendLine("| Shift | Alive | Rep p10 / p50 / p90 | Funding p10 / p50 / p90 | Cured (mean) | Deaths (mean) | Deck size | AP unused |");
                sb.AppendLine("|---|---|---|---|---|---|---|---|");
                foreach (ShiftCurvePoint c in b.Curve)
                    sb.AppendLine($"| {c.Shift} | {Pct(c.Alive)} | {F(c.Reputation.P10, "0")} / {F(c.Reputation.P50, "0")} / {F(c.Reputation.P90, "0")} | " +
                                  $"{F(c.Funding.P10, "0")} / {F(c.Funding.P50, "0")} / {F(c.Funding.P90, "0")} | {F(c.Cured.Mean)} | {F(c.Deaths.Mean)} | {F(c.DeckSize.Mean)} | {F(c.ApLeftOver, "0.00")} |");
                sb.AppendLine();

                if (b.LossesByShift.Count > 0)
                {
                    sb.AppendLine("Losses by shift: " + string.Join(", ", b.LossesByShift.OrderBy(kv => kv.Key).Select(kv => $"S{kv.Key}: {kv.Value}")) + ".");
                    sb.AppendLine("Final blow: " + string.Join(", ", b.LossCauses.OrderByDescending(kv => kv.Value).Select(kv => $"{kv.Key} {Pct(kv.Value / (double)b.Runs)}")) + ".");
                    sb.AppendLine();
                }
                sb.AppendLine("Reputation by source, per run: " + string.Join(", ", b.ReputationBySourcePerRun.OrderBy(kv => kv.Value).Select(kv => $"{kv.Key} {(kv.Value >= 0 ? "+" : "")}{F(kv.Value)}")) + ".");
                sb.AppendLine();
                sb.AppendLine($"Deaths in Triage {F(b.DeathsInTriagePerRun, "0.00")} / in Ward {F(b.DeathsInWardPerRun, "0.00")} per run. " +
                              $"Symptoms treated with cards {F(b.CardTreatmentsPerRun)}, by paging {F(b.PagesPerRun)} ({F(b.ApOnPagesPerRun)} AP). " +
                              $"Team Assessments {F(b.TeamAssessmentsPerRun)}. Spawns skipped because Triage was full {F(b.SpawnsSkippedPerRun, "0.00")}.");
                sb.AppendLine();
                if (b.CardsPlayedPerRun.Count > 0)
                {
                    sb.AppendLine("Cards played per run: " + string.Join(", ", b.CardsPlayedPerRun.Take(14).Select(kv => $"{kv.Key} {F(kv.Value)}")) + ".");
                    sb.AppendLine();
                }
                if (b.Purchases.Count > 0)
                {
                    sb.AppendLine("| Purchase | Per run | Runs buying | Win rate if bought | Win rate if not |");
                    sb.AppendLine("|---|---|---|---|---|");
                    foreach (PurchaseStats p in b.Purchases)
                        sb.AppendLine($"| {p.Item} | {F(p.PerRun, "0.00")} | {Pct(p.ShareOfRunsBuying)} | {Pct(p.WinRateWhenBought)} | {Pct(p.WinRateWhenNot)} |");
                    sb.AppendLine();
                }
            }

            if (focus != null && focus.Count > 0)
            {
                sb.AppendLine("## Dominant purchases (single-focus experiment)");
                sb.AppendLine();
                sb.AppendLine("The greedy player buys only one thing, whenever it can afford it, and nothing else. " +
                              "The `nobuy` row is the baseline. A purchase whose row is far above the others dominates.");
                sb.AppendLine();
                sb.AppendLine("| Focus | Win rate | Avg last shift | Cured / run | Deaths / run | Items bought / run |");
                sb.AppendLine("|---|---|---|---|---|---|");
                foreach (FocusResult f in focus.OrderByDescending(f => f.Summary.WinRate))
                {
                    BatchSummary b = f.Summary;
                    sb.AppendLine($"| {f.Group} | {Pct(b.WinRate)} ± {Pct(b.WinRateCi95)} | {F(b.AvgLastShift)} | {F(b.Pools.Sum(p => p.CuresPerRun))} | " +
                                  $"{F(b.Pools.Sum(p => p.DeathsPerRun))} | {F(b.Purchases.Sum(p => p.PerRun), "0.00")} |");
                }
                sb.AppendLine();
            }

            sb.AppendLine("## Config used");
            sb.AppendLine();
            sb.AppendLine(string.Join(", ", config.Describe().Select(kv => $"`{kv.Key}={kv.Value}`")));
            sb.AppendLine();
            sb.AppendLine($"Content: {data.StartingDeck.Count}-card starting deck, {data.MarketPool.Count} purchasable cards " +
                          $"({string.Join(", ", data.MarketPool.Select(c => $"{c.Name} {c.MarketPrice}F"))}), {data.RedTapePool.Count} Red Tape, " +
                          $"{data.WalkInPool.Count}/{data.AmbulancePool.Count}/{data.TraumaFlightPool.Count} Walk-In/Ambulance/Trauma patients.");
            if (data.Warnings.Count > 0)
            {
                sb.AppendLine();
                sb.AppendLine("Loader warnings:");
                foreach (string w in data.Warnings.Distinct()) sb.AppendLine("- " + w);
            }
            return sb.ToString();
        }

        public static string CurvesCsv(IReadOnlyList<BatchSummary> batches)
        {
            var sb = new StringBuilder();
            sb.AppendLine("bot,shift,alive,rep_p10,rep_p50,rep_p90,rep_mean,funding_p10,funding_p50,funding_p90,funding_mean,cured_mean,deaths_mean,deck_mean,ap_unused");
            foreach (BatchSummary b in batches)
                foreach (ShiftCurvePoint c in b.Curve)
                    sb.AppendLine(string.Join(",", b.Label, c.Shift, F(c.Alive, "0.0000"),
                        F(c.Reputation.P10, "0"), F(c.Reputation.P50, "0"), F(c.Reputation.P90, "0"), F(c.Reputation.Mean, "0.00"),
                        F(c.Funding.P10, "0"), F(c.Funding.P50, "0"), F(c.Funding.P90, "0"), F(c.Funding.Mean, "0.00"),
                        F(c.Cured.Mean, "0.00"), F(c.Deaths.Mean, "0.00"), F(c.DeckSize.Mean, "0.00"), F(c.ApLeftOver, "0.00")));
            return sb.ToString();
        }
    }
}
